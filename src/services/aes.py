def _xtime(a: int) -> int:
    a <<= 1
    return (a ^ 0x1B) & 0xFF if a & 0x100 else a


def _mul(a: int, b: int) -> int:
    """GF(2^8) multiply."""
    result = 0
    while b:
        if b & 1:
            result ^= a
        a = _xtime(a)
        b >>= 1
    return result


def _key_expansion(key: bytes, rounds: int) -> list[list[int]]:
    """AES key schedule -> list of round key words (4 bytes each)."""
    nk = len(key) // 4
    words = [list(key[i * 4 : i * 4 + 4]) for i in range(nk)]
    for i in range(nk, 4 * (rounds + 1)):
        temp = list(words[i - 1])
        if i % nk == 0:
            temp = temp[1:] + temp[:1]  # RotWord
            temp = [_SBOX[b] for b in temp]  # SubWord
            temp[0] ^= _RCON[i // nk - 1]
        elif nk > 6 and i % nk == 4:
            temp = [_SBOX[b] for b in temp]
        words.append([words[i - nk][j] ^ temp[j] for j in range(4)])
    return [words[4 * r : 4 * r + 4] for r in range(rounds + 1)]


def _add_round_key(state: list[list[int]], round_key: list[list[int]]) -> None:
    for c in range(4):
        for r in range(4):
            state[r][c] ^= round_key[c][r]


def _inv_shift_rows(state: list[list[int]]) -> None:
    for r in range(1, 4):
        state[r] = state[r][-r:] + state[r][:-r]


def _inv_sub_bytes(state: list[list[int]]) -> None:
    for r in range(4):
        for c in range(4):
            state[r][c] = _INV_SBOX[state[r][c]]


def _inv_mix_columns(state: list[list[int]]) -> None:
    for c in range(4):
        a = [state[r][c] for r in range(4)]
        state[0][c] = _mul(a[0], 14) ^ _mul(a[1], 11) ^ _mul(a[2], 13) ^ _mul(a[3], 9)
        state[1][c] = _mul(a[0], 9) ^ _mul(a[1], 14) ^ _mul(a[2], 11) ^ _mul(a[3], 13)
        state[2][c] = _mul(a[0], 13) ^ _mul(a[1], 9) ^ _mul(a[2], 14) ^ _mul(a[3], 11)
        state[3][c] = _mul(a[0], 11) ^ _mul(a[1], 13) ^ _mul(a[2], 9) ^ _mul(a[3], 14)


def _decrypt_block(block: bytes, round_keys: list[list[int]]) -> bytes:
    state = [[block[r + 4 * c] for c in range(4)] for r in range(4)]
    _add_round_key(state, round_keys[-1])
    for round_i in range(len(round_keys) - 2, 0, -1):
        _inv_shift_rows(state)
        _inv_sub_bytes(state)
        _add_round_key(state, round_keys[round_i])
        _inv_mix_columns(state)
    _inv_shift_rows(state)
    _inv_sub_bytes(state)
    _add_round_key(state, round_keys[0])
    return bytes(state[r][c] for c in range(4) for r in range(4))


def _unpad(data: bytes) -> bytes:
    if not data:
        return data
    pad = data[-1]
    if 1 <= pad <= 16 and data[-pad:] == bytes([pad]) * pad:
        return data[:-pad]
    return data  # tolerate absent padding


def aes_cbc_decrypt(key: bytes, iv: bytes, ciphertext: bytes) -> bytes:
    """AES-CBC decrypt. Key length 16/24/32 selects AES-128/192/256."""
    if len(key) not in (16, 24, 32):
        raise ValueError(f"unsupported key length {len(key)}")
    if len(ciphertext) % 16:
        raise ValueError("ciphertext must be a multiple of 16 bytes")
    rounds = {16: 10, 24: 12, 32: 14}[len(key)]
    round_keys = _key_expansion(key, rounds)
    out = bytearray()
    prev = iv
    for i in range(0, len(ciphertext), 16):
        block = ciphertext[i : i + 16]
        out += bytes(
            a ^ b
            for a, b in zip(_decrypt_block(block, round_keys), prev, strict=True)
        )
        prev = block
    return _unpad(bytes(out))
